#!/usr/bin/env bash
# Resolve the base images to immutable digests and write them to deploy/.env,
# which docker compose reads automatically (README §7.2 rule 9).
# Re-run monthly (then rebuild) to pick up OS security patches.
set -euo pipefail
cd "$(dirname "$0")"

resolve() {
  docker buildx imagetools inspect "$1" --format '{{json .Manifest}}' \
    | python3 -c 'import json,sys; print(json.load(sys.stdin)["digest"])'
}

NODE_TAG="node:26-bookworm-slim"
GIT_TAG="alpine/git:latest"

NODE_DIGEST="$(resolve "$NODE_TAG")"
GIT_DIGEST="$(resolve "$GIT_TAG")"

umask 077
{
  echo "# Generated by pin-images.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit by hand."
  echo "NODE_IMAGE=${NODE_TAG}@${NODE_DIGEST}"
  echo "GIT_IMAGE=${GIT_TAG%:*}@${GIT_DIGEST}"
  grep -E '^TZ=' .env 2>/dev/null || echo "TZ=America/Chicago"
} > .env.new
mv .env.new .env
echo "Pinned:"; cat .env
